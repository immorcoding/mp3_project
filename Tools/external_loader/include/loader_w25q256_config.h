#ifndef LOADER_W25Q256_CONFIG_H
#define LOADER_W25Q256_CONFIG_H

#include <stdint.h>

#define LOADER_W25Q256_PAGE_SIZE             0x100UL
#define LOADER_W25Q256_SECTOR_SIZE           0x1000UL
#define LOADER_W25Q256_FLASH_SIZE_POSITION   24U
#define LOADER_W25Q256_JEDEC_MANUFACTURER    0xEFU
#define LOADER_W25Q256_JEDEC_CAPACITY        0x19U

#define LOADER_W25Q256_COMMAND_WRITE_ENABLE       0x06U
#define LOADER_W25Q256_COMMAND_READ_STATUS1       0x05U
#define LOADER_W25Q256_COMMAND_READ_STATUS2       0x35U
#define LOADER_W25Q256_COMMAND_WRITE_STATUS2      0x31U
#define LOADER_W25Q256_COMMAND_READ_JEDEC_ID      0x9FU
#define LOADER_W25Q256_COMMAND_RESET_ENABLE       0x66U
#define LOADER_W25Q256_COMMAND_RESET              0x99U
#define LOADER_W25Q256_COMMAND_PAGE_PROGRAM_4BYTE 0x34U
#define LOADER_W25Q256_COMMAND_SECTOR_ERASE_4BYTE 0x21U
#define LOADER_W25Q256_COMMAND_CHIP_ERASE         0xC7U
#define LOADER_W25Q256_COMMAND_READ_4BYTE_QUAD_IO 0xECU

#define LOADER_W25Q256_STATUS1_WIP           0x01U
#define LOADER_W25Q256_STATUS1_WEL           0x02U
#define LOADER_W25Q256_STATUS2_QE            0x02U

#define LOADER_W25Q256_COMMAND_TIMEOUT_TICKS 5000U
#define LOADER_W25Q256_PROGRAM_TIMEOUT_TICKS 10U
#define LOADER_W25Q256_ERASE_TIMEOUT_TICKS   1000U
#define LOADER_W25Q256_CHIP_TIMEOUT_TICKS    300000U

#endif /* LOADER_W25Q256_CONFIG_H */
